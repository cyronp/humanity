import { assert, describe, it } from "@effect/vitest"
import { SessionId } from "@humanity/contracts"
import { humanText, importTranscript } from "../src/claude/transcript.ts"

const sessionId = SessionId.make("thread-1")
const FALLBACK = "2026-01-01T00:00:00.000Z"

const user = (content: unknown, extra: Record<string, unknown> = {}) => ({
  type: "user",
  uuid: crypto.randomUUID(),
  session_id: "cli-1",
  parent_tool_use_id: null,
  message: { role: "user", content },
  timestamp: "2026-11-10T10:00:00.000Z",
  ...extra,
})

const assistant = (content: ReadonlyArray<unknown>, timestamp = "2026-11-10T10:00:05.000Z") => ({
  type: "assistant",
  uuid: crypto.randomUUID(),
  session_id: "cli-1",
  parent_tool_use_id: null,
  message: { role: "assistant", content },
  timestamp,
})

describe("humanText", () => {
  it("drops the context Claude Code wraps around what the human typed", () => {
    assert.strictEqual(
      humanText("<system-reminder>Today is Monday.</system-reminder>\nFix the login bug"),
      "Fix the login bug",
    )
    assert.strictEqual(
      humanText("<ide_opened_file>src/a.ts</ide_opened_file> what does this do?"),
      "what does this do?",
    )
  })

  it("keeps pasted text without its wrapper", () => {
    assert.strictEqual(
      humanText('<pasted_content id="394a">\nError: boom\n</pasted_content>\nWhy?'),
      "Error: boom\n\nWhy?",
    )
  })

  it("shows a slash command as the human typed it", () => {
    assert.strictEqual(
      humanText(
        "<command-name>/review</command-name>\n<command-message>review</command-message>\n<command-args>42</command-args>",
      ),
      "/review 42",
    )
    assert.strictEqual(
      humanText("<command-name>/init</command-name><command-args></command-args>"),
      "/init",
    )
  })
})

describe("importTranscript", () => {
  it("turns a conversation into messages and finished tool calls", () => {
    const imported = importTranscript(
      sessionId,
      [
        user("Read the README", { origin: { kind: "human" } }),
        assistant([
          { type: "thinking", thinking: "Let me look.", signature: "x" },
          { type: "tool_use", id: "toolu_1", name: "Read", input: { file_path: "README.md" } },
        ]),
        user([{ type: "tool_result", tool_use_id: "toolu_1", content: "# Hello" }], {
          timestamp: "2026-11-10T10:00:06.000Z",
        }),
        assistant([{ type: "text", text: "It says hello." }], "2026-11-10T10:00:07.000Z"),
      ],
      FALLBACK,
    )

    assert.isTrue(imported.hasConversation)
    assert.deepStrictEqual(
      imported.messages.map(({ message }) => message.content._tag),
      ["user", "assistant", "tool_results", "assistant"],
    )
    assert.deepStrictEqual(imported.messages[0]?.message.content, {
      _tag: "user",
      text: "Read the README",
    })
    assert.strictEqual(imported.messages[3]?.message.createdAt, "2026-11-10T10:00:07.000Z")
    // Ids are unique across threads and stable across refreshes of the same one.
    assert.deepStrictEqual(
      imported.messages.map(({ message }) => message.id),
      ["thread-1:0", "thread-1:1", "thread-1:2", "thread-1:3"],
    )

    assert.strictEqual(imported.toolCalls.length, 1)
    const call = imported.toolCalls[0]
    assert.strictEqual(call?.toolName, "Read")
    assert.strictEqual(call?.status, "succeeded")
    assert.strictEqual(call?.output?.content, "# Hello")
    assert.strictEqual(call?.startedAt, "2026-11-10T10:00:05.000Z")
    assert.strictEqual(call?.finishedAt, "2026-11-10T10:00:06.000Z")
  })

  it("leaves out what Claude Code wrote itself: commands, their output, notifications", () => {
    const imported = importTranscript(
      sessionId,
      [
        user("<command-name>/model</command-name><command-args></command-args>", {
          isCompletedLocalCommand: true,
        }),
        user("<local-command-stdout>Set model to Opus</local-command-stdout>", {
          isCompletedLocalCommand: true,
        }),
        user("<local-command-caveat>Caveat: generated by commands.</local-command-caveat>"),
        user("Expanded skill prompt", { isMeta: true }),
        user("<task-notification><task-id>b1</task-id></task-notification>", {
          origin: { kind: "task-notification" },
        }),
        user("[Subagent hand-back] The report follows", { origin: { kind: "peer" } }),
      ],
      FALLBACK,
    )
    assert.isFalse(imported.hasConversation)
    assert.strictEqual(imported.messages.length, 0)
  })

  it("marks interruptions, counts images, and fails calls that never got a result", () => {
    const imported = importTranscript(
      sessionId,
      [
        user([
          { type: "text", text: "What is in this screenshot?" },
          { type: "image", source: { type: "base64", media_type: "image/png", data: "AAAA" } },
        ]),
        assistant([{ type: "tool_use", id: "toolu_2", name: "Bash", input: { command: "ls" } }]),
        user([{ type: "text", text: "[Request interrupted by user for tool use]" }]),
      ],
      FALLBACK,
    )
    assert.deepStrictEqual(imported.messages[0]?.message.content, {
      _tag: "user",
      text: "What is in this screenshot?\n\n[1 image]",
    })
    assert.deepStrictEqual(imported.messages[2]?.message.content, {
      _tag: "notice",
      level: "warning",
      text: "Interrupted by the human.",
    })
    assert.strictEqual(imported.toolCalls[0]?.status, "failed")
    assert.isNull(imported.toolCalls[0]?.finishedAt)
  })

  it("dates entries without a timestamp like the one before them", () => {
    const imported = importTranscript(
      sessionId,
      [user("first", { timestamp: undefined }), user("second"), user("third", { timestamp: "?" })],
      FALLBACK,
    )
    assert.deepStrictEqual(
      imported.messages.map(({ message }) => message.createdAt),
      [FALLBACK, "2026-11-10T10:00:00.000Z", "2026-11-10T10:00:00.000Z"],
    )
  })
})
